# ============================================================
# ML Assignment 2
# Dry Bean Classification - Streamlit Application
#
# This application loads pre-trained machine learning models
# and evaluates them using an uploaded test CSV file.
# ============================================================

import os
import joblib
import numpy as np
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    matthews_corrcoef,
    roc_auc_score,
    confusion_matrix,
    classification_report
)


# ============================================================
# 1. PAGE CONFIGURATION
# ============================================================

st.set_page_config(
    page_title="Dry Bean Classification",
    page_icon="🌱",
    layout="wide"
)


# ============================================================
# 2. PAGE TITLE
# ============================================================

st.title("🌱 Dry Bean Classification")
st.subheader("Machine Learning Model Evaluation")

st.write(
    """
    This application evaluates pre-trained machine learning models
    for classifying dry beans using morphological characteristics.

    Upload a test CSV file, select a machine learning model,
    and click **Evaluate Model** to view the model performance.
    """
)


# ============================================================
# 3. MODEL PATHS
# ============================================================

MODEL_DIR = "model"

MODEL_PATHS = {
    "Logistic Regression":
        os.path.join(MODEL_DIR, "logistic_regression.pkl"),

    "Decision Tree":
        os.path.join(MODEL_DIR, "decision_tree.pkl"),

    "KNN":
        os.path.join(MODEL_DIR, "knn.pkl"),

    "Naive Bayes":
        os.path.join(MODEL_DIR, "naive_bayes.pkl"),

    "SVM":
        os.path.join(MODEL_DIR, "svm.pkl")
}


# ============================================================
# 4. LOAD SUPPORTING OBJECTS
# ============================================================

@st.cache_resource
def load_supporting_objects():

    scaler = joblib.load(
        os.path.join(MODEL_DIR, "scaler.pkl")
    )

    label_encoder = joblib.load(
        os.path.join(MODEL_DIR, "label_encoder.pkl")
    )

    feature_names = joblib.load(
        os.path.join(MODEL_DIR, "feature_names.pkl")
    )

    return scaler, label_encoder, feature_names


# ============================================================
# 5. LOAD MACHINE LEARNING MODEL
# ============================================================

@st.cache_resource
def load_model(model_name):

    model_path = MODEL_PATHS[model_name]

    model = joblib.load(model_path)

    return model


# ============================================================
# 6. LOAD REQUIRED OBJECTS
# ============================================================

try:

    scaler, label_encoder, feature_names = (
        load_supporting_objects()
    )

except Exception as e:

    st.error(
        "Unable to load the saved preprocessing files."
    )

    st.error(str(e))

    st.stop()


# ============================================================
# 7. SIDEBAR
# ============================================================

st.sidebar.header("Model Configuration")

selected_model = st.sidebar.selectbox(
    "Select Machine Learning Model",
    [
        "Logistic Regression",
        "Decision Tree",
        "KNN",
        "Naive Bayes",
        "SVM"
    ]
)


# Models that require StandardScaler.
SCALED_MODELS = [
    "Logistic Regression",
    "KNN",
    "SVM"
]


st.sidebar.markdown("---")

st.sidebar.write("### Model Information")

model_descriptions = {

    "Logistic Regression":
        "Linear classification model using scaled input features.",

    "Decision Tree":
        "Tree-based classification model.",

    "KNN":
        "Distance-based classifier using scaled input features.",

    "Naive Bayes":
        "Gaussian probabilistic classification model.",

    "SVM":
        "Support Vector Machine with an RBF kernel using scaled input features."
}


st.sidebar.info(
    model_descriptions[selected_model]
)


# ============================================================
# 8. FILE UPLOAD
# ============================================================

st.header("1. Upload Test Data")

uploaded_file = st.file_uploader(
    "Upload the test CSV file",
    type=["csv"],
    help="You can use the test_data.csv generated by train_models.py"
)


# ============================================================
# 9. PROCESS UPLOADED CSV
# ============================================================

if uploaded_file is not None:

    try:

        data = pd.read_csv(uploaded_file)

    except Exception as e:

        st.error("Could not read the uploaded CSV file.")
        st.error(str(e))
        st.stop()


    st.success("CSV file uploaded successfully.")


    # ========================================================
    # 10. DISPLAY DATASET INFORMATION
    # ========================================================

    st.header("2. Test Dataset")

    col1, col2, col3 = st.columns(3)

    col1.metric(
        "Number of Rows",
        data.shape[0]
    )

    col2.metric(
        "Number of Columns",
        data.shape[1]
    )

    col3.metric(
        "Number of Features",
        len(feature_names)
    )


    # ========================================================
    # 11. DATA PREVIEW
    # ========================================================

    with st.expander(
        "Preview Uploaded Dataset",
        expanded=False
    ):

        st.dataframe(
            data.head(20),
            use_container_width=True
        )


    # ========================================================
    # 12. VALIDATE CLASS COLUMN
    # ========================================================

    if "Class" not in data.columns:

        st.error(
            """
            The uploaded CSV must contain a column named 'Class'
            so that the application can calculate the evaluation
            metrics.
            """
        )

        st.stop()


    # ========================================================
    # 13. VALIDATE FEATURE COLUMNS
    # ========================================================

    missing_features = [
        feature
        for feature in feature_names
        if feature not in data.columns
    ]


    if missing_features:

        st.error(
            "The uploaded CSV is missing required features:"
        )

        st.write(missing_features)

        st.stop()


    # ========================================================
    # 14. EXTRACT FEATURES AND TARGET
    # ========================================================

    # Select features in exactly the same order as they were
    # used while training the machine learning models.
    X_test = data[feature_names].copy()

    # Actual class labels from uploaded test data.
    y_test_original = data["Class"].copy()


    # ========================================================
    # 15. CHECK MISSING VALUES
    # ========================================================

    missing_values = X_test.isnull().sum().sum()

    if missing_values > 0:

        st.error(
            f"The uploaded dataset contains "
            f"{missing_values} missing feature values."
        )

        st.stop()


    # ========================================================
    # 16. VALIDATE CLASS LABELS
    # ========================================================

    known_classes = set(label_encoder.classes_)

    uploaded_classes = set(
        y_test_original.astype(str).unique()
    )

    unknown_classes = (
        uploaded_classes - known_classes
    )


    if unknown_classes:

        st.error(
            "The uploaded file contains unknown class labels:"
        )

        st.write(sorted(unknown_classes))

        st.write(
            "Expected classes:",
            list(label_encoder.classes_)
        )

        st.stop()


    # Convert original textual classes to numeric labels.
    y_test = label_encoder.transform(
        y_test_original
    )


    # ========================================================
    # 17. MODEL SELECTION DISPLAY
    # ========================================================

    st.header("3. Model Selection")

    st.write(
        f"Selected model: **{selected_model}**"
    )


    # ========================================================
    # 18. EVALUATE MODEL BUTTON
    # ========================================================

    evaluate_button = st.button(
        "Evaluate Model",
        type="primary"
    )


    if evaluate_button:

        # ====================================================
        # 19. LOAD MODEL
        # ====================================================

        try:

            model = load_model(
                selected_model
            )

        except Exception as e:

            st.error(
                f"Unable to load {selected_model}."
            )

            st.error(str(e))

            st.stop()


        # ====================================================
        # 20. APPLY FEATURE SCALING WHEN REQUIRED
        # ====================================================

        if selected_model in SCALED_MODELS:

            X_prediction = scaler.transform(
                X_test
            )

        else:

            X_prediction = X_test


        # ====================================================
        # 21. GENERATE PREDICTIONS
        # ====================================================

        try:

            y_pred = model.predict(
                X_prediction
            )

            y_probability = model.predict_proba(
                X_prediction
            )

        except Exception as e:

            st.error(
                "An error occurred while generating predictions."
            )

            st.error(str(e))

            st.stop()


        # ====================================================
        # 22. CALCULATE PERFORMANCE METRICS
        # ====================================================

        accuracy = accuracy_score(
            y_test,
            y_pred
        )

        precision = precision_score(
            y_test,
            y_pred,
            average="weighted",
            zero_division=0
        )

        recall = recall_score(
            y_test,
            y_pred,
            average="weighted",
            zero_division=0
        )

        f1 = f1_score(
            y_test,
            y_pred,
            average="weighted",
            zero_division=0
        )

        mcc = matthews_corrcoef(
            y_test,
            y_pred
        )


        # ====================================================
        # 23. CALCULATE MULTICLASS AUC
        # ====================================================

        try:

            auc = roc_auc_score(
                y_test,
                y_probability,
                multi_class="ovr",
                average="weighted",
                labels=model.classes_
            )

        except ValueError:

            # AUC may be unavailable when the uploaded file
            # does not contain every target class.
            auc = None


        # ====================================================
        # 24. DISPLAY PERFORMANCE METRICS
        # ====================================================

        st.header("4. Model Performance")

        metric_col1, metric_col2, metric_col3 = st.columns(3)

        metric_col1.metric(
            "Accuracy",
            f"{accuracy:.4f}"
        )

        if auc is not None:

            metric_col2.metric(
                "AUC",
                f"{auc:.4f}"
            )

        else:

            metric_col2.metric(
                "AUC",
                "N/A"
            )

        metric_col3.metric(
            "Precision",
            f"{precision:.4f}"
        )


        metric_col4, metric_col5, metric_col6 = st.columns(3)

        metric_col4.metric(
            "Recall",
            f"{recall:.4f}"
        )

        metric_col5.metric(
            "F1 Score",
            f"{f1:.4f}"
        )

        metric_col6.metric(
            "MCC",
            f"{mcc:.4f}"
        )


        # ====================================================
        # 25. METRICS TABLE
        # ====================================================

        st.subheader("Performance Summary")

        metrics_data = {
            "Metric": [
                "Accuracy",
                "AUC",
                "Precision",
                "Recall",
                "F1 Score",
                "MCC"
            ],

            "Score": [
                round(accuracy, 4),
                round(auc, 4)
                if auc is not None
                else "N/A",
                round(precision, 4),
                round(recall, 4),
                round(f1, 4),
                round(mcc, 4)
            ]
        }

        metrics_df = pd.DataFrame(
            metrics_data
        )

        st.dataframe(
            metrics_df,
            use_container_width=True,
            hide_index=True
        )


        # ====================================================
        # 26. CONFUSION MATRIX
        # ====================================================

        st.header("5. Confusion Matrix")

        # Use every encoded class so matrix ordering is stable.
        class_indices = np.arange(
            len(label_encoder.classes_)
        )

        cm = confusion_matrix(
            y_test,
            y_pred,
            labels=class_indices
        )


        fig, ax = plt.subplots(
            figsize=(10, 7)
        )

        sns.heatmap(
            cm,
            annot=True,
            fmt="d",
            cmap="Blues",
            xticklabels=label_encoder.classes_,
            yticklabels=label_encoder.classes_,
            ax=ax
        )

        ax.set_xlabel(
            "Predicted Class"
        )

        ax.set_ylabel(
            "Actual Class"
        )

        ax.set_title(
            f"Confusion Matrix - {selected_model}"
        )

        plt.xticks(
            rotation=45,
            ha="right"
        )

        plt.yticks(
            rotation=0
        )

        plt.tight_layout()

        st.pyplot(fig)

        plt.close(fig)


        # ====================================================
        # 27. CLASSIFICATION REPORT
        # ====================================================

        st.header(
            "6. Classification Report"
        )


        report = classification_report(
            y_test,
            y_pred,
            labels=class_indices,
            target_names=label_encoder.classes_,
            output_dict=True,
            zero_division=0
        )


        report_df = pd.DataFrame(
            report
        ).transpose()


        st.dataframe(
            report_df.round(4),
            use_container_width=True
        )


        # ====================================================
        # 28. CONVERT PREDICTIONS BACK TO BEAN NAMES
        # ====================================================

        predicted_classes = (
            label_encoder.inverse_transform(
                y_pred.astype(int)
            )
        )


        # ====================================================
        # 29. PREDICTION RESULTS
        # ====================================================

        st.header(
            "7. Prediction Results"
        )


        prediction_results = pd.DataFrame({

            "Actual Class":
                y_test_original.values,

            "Predicted Class":
                predicted_classes
        })


        prediction_results["Correct Prediction"] = np.where(
            prediction_results["Actual Class"]
            ==
            prediction_results["Predicted Class"],
            "Yes",
            "No"
        )


        st.dataframe(
            prediction_results,
            use_container_width=True
        )


        # ====================================================
        # 30. PREDICTION SUMMARY
        # ====================================================

        correct_predictions = (
            prediction_results[
                "Correct Prediction"
            ] == "Yes"
        ).sum()


        incorrect_predictions = (
            prediction_results[
                "Correct Prediction"
            ] == "No"
        ).sum()


        summary_col1, summary_col2 = st.columns(2)


        summary_col1.metric(
            "Correct Predictions",
            int(correct_predictions)
        )


        summary_col2.metric(
            "Incorrect Predictions",
            int(incorrect_predictions)
        )


        # ====================================================
        # 31. DOWNLOAD PREDICTIONS
        # ====================================================

        st.header(
            "8. Download Results"
        )


        # Add predictions to a copy of the original
        # uploaded dataset.
        downloadable_results = data.copy()

        downloadable_results[
            "Predicted_Class"
        ] = predicted_classes


        downloadable_results[
            "Correct_Prediction"
        ] = np.where(
            downloadable_results["Class"]
            ==
            downloadable_results[
                "Predicted_Class"
            ],
            "Yes",
            "No"
        )


        csv = downloadable_results.to_csv(
            index=False
        ).encode("utf-8")


        st.download_button(
            label="Download Prediction Results",
            data=csv,
            file_name="prediction_results.csv",
            mime="text/csv"
        )


        # ====================================================
        # 32. COMPLETION MESSAGE
        # ====================================================

        st.success(
            f"{selected_model} evaluation completed successfully."
        )


# ============================================================
# 33. MESSAGE WHEN NO FILE HAS BEEN UPLOADED
# ============================================================

else:

    st.info(
        """
        Upload the test_data.csv file generated by
        train_models.py to begin the model evaluation.
        """
    )


# ============================================================
# 34. FOOTER
# ============================================================

st.markdown("---")

st.caption(
    "Dry Bean Classification | Machine Learning Assignment 2"
)